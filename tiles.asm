DRAW_TILE_ID:
    PUSH BC
    LD L,A
    LD H,0
    ADD HL,HL
    LD DE,TILE_POINTERS
    ADD HL,DE
    LD E,(HL)
    INC HL
    LD D,(HL)
    POP BC
    CALL GET_SCREEN_ADDR
    PUSH HL
    PUSH DE
    CALL DRAW_1_1
    POP DE
    POP HL
    EX DE,HL
    LD BC,8
    ADD HL,BC
    EX DE,HL
    JP RESTORE_ATTR_1_1

; IN HL=tile map, B=top Y, C=left X, D=width, E=height.
; Static tile scene is rendered once at startup.
DRAW_TILE_MAP:
    LD (TILE_MAP_CURSOR),HL
    LD (TILE_DRAW_POS),BC
    LD A,C
    LD (TILE_MAP_LEFT),A
    LD A,D
    LD (TILE_MAP_WIDTH),A
    LD A,E
    LD (TILE_ROWS_LEFT),A
.ROW:
    LD A,(TILE_MAP_WIDTH)
    LD (TILE_COLS_LEFT),A
.COL:
    LD HL,(TILE_MAP_CURSOR)
    LD A,(HL)
    INC HL
    LD (TILE_MAP_CURSOR),HL
    LD BC,(TILE_DRAW_POS)
    CALL DRAW_TILE_ID
    LD HL,TILE_DRAW_POS
    INC (HL)
    LD HL,TILE_COLS_LEFT
    DEC (HL)
    JR NZ,.COL
    LD A,(TILE_MAP_LEFT)
    LD (TILE_DRAW_POS),A
    LD HL,TILE_DRAW_POS+1
    INC (HL)
    LD HL,TILE_ROWS_LEFT
    DEC (HL)
    JR NZ,.ROW
    RET

