; Short-lived 8x8 sparks where a player shot meets a hostile shot.
; Four independent slots, 3 animation frames x 3 game ticks.
; Every live spark is dirty each tick: moving stars cannot erase it.
IMP_ACTIVE EQU 0
IMP_X      EQU 1
IMP_Y      EQU 2
IMP_DRAWN  EQU 3
IMP_DIRTY  EQU 4
IMP_FRAME  EQU 5
IMP_TIMER  EQU 6
IMP_SIZE   EQU 7
MAX_IMPACTS EQU 4
IMPACT_FRAME_TICKS EQU 3
IMPACT_FRAME_COUNT EQU 3

RESET_BULLET_IMPACTS:
    LD HL,IMPACT_POOL
    LD (HL),0
    LD DE,IMPACT_POOL+1
    LD BC,MAX_IMPACTS*IMP_SIZE-1
    LDIR
    RET

; IN B=impact Y, C=impact X. Preserve BC,DE,IX,IY.
SPAWN_BULLET_IMPACT:
    PUSH BC
    PUSH DE
    PUSH IX
    LD D,B
    LD E,C
    LD IX,IMPACT_POOL
    LD B,MAX_IMPACTS
.FIND:
    LD A,(IX+IMP_ACTIVE)
    OR A
    JR NZ,.NEXT
    LD A,(IX+IMP_DRAWN)
    OR A
    JR NZ,.NEXT
    LD (IX+IMP_X),E
    LD (IX+IMP_Y),D
    XOR A
    LD (IX+IMP_FRAME),A
    LD A,IMPACT_FRAME_TICKS
    LD (IX+IMP_TIMER),A
    LD A,1
    LD (IX+IMP_ACTIVE),A
    LD (IX+IMP_DIRTY),A
    JR .DONE
.NEXT:
    PUSH DE
    LD DE,IMP_SIZE
    ADD IX,DE
    POP DE
    DJNZ .FIND
.DONE:
    POP IX
    POP DE
    POP BC
    RET

UPDATE_BULLET_IMPACTS:
    LD IX,IMPACT_POOL
    LD B,MAX_IMPACTS
.NEXT:
    PUSH BC
    LD A,(IX+IMP_ACTIVE)
    OR A
    JR Z,.SKIP
    LD A,1
    LD (IX+IMP_DIRTY),A
    DEC (IX+IMP_TIMER)
    JR NZ,.SKIP
    LD A,IMPACT_FRAME_TICKS
    LD (IX+IMP_TIMER),A
    LD A,(IX+IMP_FRAME)
    INC A
    CP IMPACT_FRAME_COUNT
    JR NZ,.NEXT_FRAME
    XOR A
    LD (IX+IMP_ACTIVE),A
    JR .SKIP
.NEXT_FRAME:
    LD (IX+IMP_FRAME),A
.SKIP:
    POP BC
    LD DE,IMP_SIZE
    ADD IX,DE
    DJNZ .NEXT
    RET

RENDER_ERASE_BULLET_IMPACTS:
    LD IX,IMPACT_POOL
    LD B,MAX_IMPACTS
.NEXT:
    PUSH BC
    LD A,(IX+IMP_DIRTY)
    OR A
    JR Z,.SKIP
    LD A,(IX+IMP_DRAWN)
    OR A
    JR Z,.NEW
    LD B,(IX+IMP_Y)
    LD C,(IX+IMP_X)
    LD DE,#0101
    CALL STARFIELD_MARK_RECT
    XOR A
    LD (IX+IMP_DRAWN),A
.NEW:
    LD A,(IX+IMP_ACTIVE)
    OR A
    JR Z,.SKIP
    LD B,(IX+IMP_Y)
    LD C,(IX+IMP_X)
    LD DE,#0101
    CALL STARFIELD_MARK_RECT
.SKIP:
    POP BC
    LD DE,IMP_SIZE
    ADD IX,DE
    DJNZ .NEXT
    RET

RENDER_DRAW_BULLET_IMPACTS:
    LD IX,IMPACT_POOL
    LD B,MAX_IMPACTS
.NEXT:
    PUSH BC
    LD A,(IX+IMP_DIRTY)
    OR A
    JR Z,.SKIP
    XOR A
    LD (IX+IMP_DIRTY),A
    LD A,(IX+IMP_ACTIVE)
    OR A
    JR Z,.SKIP
    LD B,(IX+IMP_Y)
    LD C,(IX+IMP_X)
    CALL GET_SCREEN_ADDR
    PUSH HL
    LD A,(IX+IMP_FRAME)
    LD E,A
    LD D,0
    LD HL,IMPACT_COLOURS
    ADD HL,DE
    LD A,(HL)
    LD (IMPACT_DRAW_ATTR),A
    POP HL
    LD DE,IMPACT_DRAW_ATTR
    CALL RESTORE_ATTR_1_1
    PUSH HL
    LD A,(IX+IMP_FRAME)
    ADD A,A
    ADD A,A
    ADD A,A
    LD E,A
    LD D,0
    LD HL,IMPACT_IMAGES
    ADD HL,DE
    EX DE,HL
    POP HL
    CALL DRAW_1_1
    LD A,1
    LD (IX+IMP_DRAWN),A
.SKIP:
    POP BC
    LD DE,IMP_SIZE
    ADD IX,DE
    DJNZ .NEXT
    RET

IMPACT_POOL: DS MAX_IMPACTS*IMP_SIZE,0
IMPACT_DRAW_ATTR: DB #47
IMPACT_COLOURS: DB #47,#46,#42
IMPACT_IMAGES:
    DB %00011000,%00111100,%01111110,%11111111
    DB %11111111,%01111110,%00111100,%00011000
    DB %10011001,%01011010,%00111100,%11111111
    DB %11111111,%00111100,%01011010,%10011001
    DB %10000001,%00100100,%00011000,%01000010
    DB %01000010,%00011000,%00100100,%10000001
